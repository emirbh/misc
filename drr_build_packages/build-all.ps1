function Invoke-Build([string]$Name, [string]$Dir, [string[]]$Extra = @()) {
    Write-Host "==> $Name"
    if (-not (Test-Path $Dir)) { Write-Warning "FAILED: $Name - $Dir not found"; $Failed.Add($Name); return }
    $log = Join-Path $Logs "$Name.log"
    $ErrorActionPreference = 'Continue'
    Push-Location $Dir
    try { & mvn @Mvn clean install @Extra 2>&1 | Out-File -FilePath $log -Encoding utf8 }
    finally { Pop-Location }
    if ($LASTEXITCODE -ne 0) { Write-Warning "FAILED: $Name - see $log"; $Failed.Add($Name) }
}

# rune-dsl and rune-common tags carry placeholder versions (e.g.
# 0.0.0.9.x.x-SNAPSHOT). Their release pipelines set the real version before
# building; so does this.
function Set-ProjectVersion([string]$Name, [string]$Dir, [string]$Version) {
    Write-Host "==> ${Name}: set version $Version"
    $log = Join-Path $Logs "$Name-set-version.log"
    $ErrorActionPreference = 'Continue'
    Push-Location $Dir
    try { & mvn @Mvn versions:set '-DgenerateBackupPoms=true' '-DallowSnapshots=true' "-DnewVersion=$Version" 2>&1 | Out-File -FilePath $log -Encoding utf8 }
    finally { Pop-Location }
    if ($LASTEXITCODE -ne 0) { Write-Warning "FAILED: $Name set version - see $log"; $Failed.Add("$Name-set-version") }
}

# ---- No Rune code generation ----------------------------------------------------
# The generated Java of CDM, DRR, ISO 20022 and FpML is taken from each model's
# published sources, so the Rune code generator (rune-lang, rune-maven-plugin, and
# through them Xtext, Xcore and EMF) is neither built nor downloaded. The published
# POMs still declare it: as a build plugin, as dependencies the code does not use,
# and transitively through ingest-test-framework. Those declarations are removed
# from a project's POMs before it is built; Restore-Src puts the originals back.
$RegexOpts = [System.Text.RegularExpressions.RegexOptions]::Singleline

function Update-Pom([string]$File, [scriptblock]$Transform) {
    $text = [IO.File]::ReadAllText($File)
    $new = & $Transform $text
    if ($new -ne $text) { Save-Original $File; [IO.File]::WriteAllText($File, $new) }
}

function Remove-Generator([string]$Dir) {
    foreach ($m in (Get-ModuleDirs $Dir)) {
            Update-Pom (Join-Path $m 'pom.xml') {
                param($t)
                $t = [regex]::Replace($t, '\s*<plugin>\s*(?:<groupId>[^<]*</groupId>\s*)?<artifactId>(?:rosetta|rune)-maven-plugin</artifactId>.*?</plugin>', '', $RegexOpts)
                $t = [regex]::Replace($t, '\s*<dependency>\s*<groupId>[^<]*</groupId>\s*<artifactId>(?:com\.regnosys\.rosetta(?:\.tests|\.xcore|\.tools|\.ide)?|rosetta-maven-plugin|rosetta-testing|rune-(?:lang|maven-plugin|testing|xcore-plugin-dependencies|generator-api|tools|ide))</artifactId>(?:(?!</dependency>).)*</dependency>', '', $RegexOpts)
                $evaluator = [System.Text.RegularExpressions.MatchEvaluator] {
                    param($m)
                    $all = '<exclusion><groupId>*</groupId><artifactId>*</artifactId></exclusion>'
                    $body = $m.Groups[2].Value
                    if ($body.Contains('<exclusions>')) { $body = $body.Replace('<exclusions>', "<exclusions>$all") }
                    else { $body = "$body<exclusions>$all</exclusions>" }
                    $m.Groups[1].Value + $body + $m.Groups[3].Value
                }
                [regex]::Replace($t, '(<dependency>\s*<groupId>com\.regnosys</groupId>\s*<artifactId>ingest-test-framework</artifactId>)((?:(?!</dependency>).)*)(</dependency>)', $evaluator, $RegexOpts)
            }
        }
}

# A Rosetta model project rebuilt from its published sources: parent POM, then
# the rosetta-source module. Checkstyle and license-header checks need config
# files that are not part of the published sources, so they are skipped.
function Invoke-ModelBuild([string]$Name, [string]$Dir, [string[]]$Extra = @()) {
    Remove-Generator $Dir
    Invoke-Build "$Name-parent" $Dir @('-N', '-Dcheckstyle.skip', '-Dlicense.skip=true')
    Invoke-Build $Name (Join-Path $Dir 'rosetta-source') (@('-Dcheckstyle.skip', '-Dlicense.skip=true') + $Extra)
}

