# 3. rune-runtime: the library all generated model code runs on (com.rosetta.model.lib).
# Only this module of rune-dsl is built, with its com.regnosys.rosetta.lib backport.
# Its POM runs the Xtend compiler, which needs Xtext and EMF; 9.85.1 has no Xtend
# sources, and 9.83.0 has one (MapperMaths.xtend), whose Xtend-generated Java is
# taken from the published sources jar instead. So the Xtend compiler is removed.
function Build-RuneRuntime([string]$Version) {
    $dsl = Join-Path $Src "rune-dsl-$Version"
    $pom = Join-Path $dsl 'rune-runtime/pom.xml'
    if (Test-Path $pom) {
        Update-Pom $pom { param($t) [regex]::Replace($t, '\s*<plugin>\s*<groupId>org\.eclipse\.xtend</groupId>\s*<artifactId>xtend-maven-plugin</artifactId>(?:(?!</plugin>).)*</plugin>', '', $RegexOpts) }
    }
    $gen = Join-Path $Src "rune-dsl-$Version-xtend-gen/rune-runtime/src/main/java"
    if (Test-Path $gen) {
        $genFull = (Resolve-Path $gen).Path
        Get-ChildItem -LiteralPath $genFull -Recurse -Filter '*.java' -File | ForEach-Object {
            $dest = Join-Path (Join-Path $dsl 'rune-runtime/src/main/java') $_.FullName.Substring($genFull.Length + 1)
            New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
            Copy-Item -LiteralPath $_.FullName -Destination $dest -Force
        }
    }
    Set-ProjectVersion "rune-runtime-$Version" $dsl $Version
    Invoke-Build "rune-runtime-$Version" $dsl @('-pl', 'rune-runtime', '-am')
    Set-ProjectVersion "rosetta-runtime-$Version" (Join-Path $dsl 'rosetta-backport') $Version
    Invoke-Build "rosetta-runtime-$Version" (Join-Path $dsl 'rosetta-backport') @('-pl', 'rosetta-runtime', '-am')
}
