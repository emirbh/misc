	@Override
	public List<ValidationResult<?>> getValidationResults(RosettaPath path, HarmonizedData o) {
		return getComparisonResults(o)
			.stream()
			.map(res -> {
				if (!isNullOrEmpty(res.getError())) {
					return failure("HarmonizedData", ValidationResult.ValidationType.TYPE_FORMAT, "HarmonizedData", path, "", res.getError());
				}
				return success("HarmonizedData", ValidationResult.ValidationType.TYPE_FORMAT, "HarmonizedData", path, "");
			})
			.collect(toList());
	}

