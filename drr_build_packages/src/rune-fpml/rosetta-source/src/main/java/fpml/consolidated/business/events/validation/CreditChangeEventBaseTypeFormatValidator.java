package fpml.consolidated.business.events.validation;

import com.google.common.collect.Lists;
import com.rosetta.model.lib.expression.ComparisonResult;
import com.rosetta.model.lib.path.RosettaPath;
import com.rosetta.model.lib.validation.ValidationResult;
import com.rosetta.model.lib.validation.Validator;
import fpml.consolidated.business.events.CreditChangeEventBase;
import java.util.List;

import static com.google.common.base.Strings.isNullOrEmpty;
import static com.rosetta.model.lib.validation.ValidationResult.failure;
import static com.rosetta.model.lib.validation.ValidationResult.success;
import static java.util.stream.Collectors.toList;

public class CreditChangeEventBaseTypeFormatValidator implements Validator<CreditChangeEventBase> {

	private List<ComparisonResult> getComparisonResults(CreditChangeEventBase o) {
		return Lists.<ComparisonResult>newArrayList(
			);
	}

	@Override
	public List<ValidationResult<?>> getValidationResults(RosettaPath path, CreditChangeEventBase o) {
		return getComparisonResults(o)
			.stream()
			.map(res -> {
				if (!isNullOrEmpty(res.getError())) {
					return failure("CreditChangeEventBase", ValidationResult.ValidationType.TYPE_FORMAT, "CreditChangeEventBase", path, "", res.getError());
				}
				return success("CreditChangeEventBase", ValidationResult.ValidationType.TYPE_FORMAT, "CreditChangeEventBase", path, "");
			})
			.collect(toList());
	}

}
